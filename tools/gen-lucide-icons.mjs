#!/usr/bin/env node
/**
 * gen-lucide-icons.mjs — generate `src/ribbon/icons.rs` (Lucide SVG inner markup) for every
 * icon named by the ribbon spec.
 *
 * The icon NAMES come from `apps/web/apps/ribbon-leptos/src/ribbon/spec.rs`
 * (every `icon: "Name"` on a `Kind::Button` and every `icon: Some("Name")` on a `Kind::Dropdown`).
 * The SVG DATA is the tracked `apps/web/apps/ribbon-leptos/tools/lucide-icons.json`
 * (lucide-react 1.23.0 `__iconNode`, ISC license; tags are only circle/line/path/rect).
 *
 * Output: `apps/web/apps/ribbon-leptos/src/ribbon/icons.rs` —
 *   `pub const NAMES: &[&str]` (sorted, unique) and
 *   `pub fn svg(name: &str) -> Option<&'static str>` (a match over every name returning the
 *   inner SVG markup — each node `<tag attr="value" .../>`, attributes in JSON order, with
 *   `&`/`<`/`>`/`"` escaped). The file is piped through `rustfmt --edition 2021` so `--check`
 *   and `cargo fmt` can never disagree.
 *
 * Usage: node tools/gen-lucide-icons.mjs          # write src/ribbon/icons.rs
 *        node tools/gen-lucide-icons.mjs --check  # exit 1 if the committed file is stale
 *
 * No runtime dependencies (a fresh worktree has no node_modules): plain `node:fs` + regex.
 * Run from the repo root; both input paths are fixed relative to the repo root.
 */
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SPEC = path.resolve(ROOT, "apps/web/apps/ribbon-leptos/src/ribbon/spec.rs");
const LUCIDE = path.resolve(ROOT, "apps/web/apps/ribbon-leptos/tools/lucide-icons.json");
const OUT = path.resolve(ROOT, "apps/web/apps/ribbon-leptos/src/ribbon/icons.rs");
const CHECK = process.argv.includes("--check") || process.argv.includes("check");

/// Read the spec and collect every icon name a `Kind::Button`/`Kind::Dropdown` carries.
/// spec.rs is generated Rust: `icon: "Name"` (Button) and `icon: Some("Name")` (Dropdown) are
/// the only places an icon field appears, so one regex captures both.
function specIconNames() {
  const src = fs.readFileSync(SPEC, "utf8");
  const re = /icon:\s*(?:Some\()?"([A-Za-z0-9]+)"/g;
  const names = new Set();
  let m;
  while ((m = re.exec(src)) !== null) names.add(m[1]);
  return [...names].sort();
}

/// Escape a value for an XML attribute: `&` first, then `<`, `>`, `"`.
const escAttr = (v) =>
  String(v)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/// Inner SVG markup for one icon node: `<tag attr="v" .../>` (attributes in JSON order).
function nodeMarkup([tag, attrs]) {
  const a = Object.entries(attrs)
    .map(([k, v]) => `${k}="${escAttr(v)}"`)
    .join(" ");
  return a ? `<${tag} ${a}/>` : `<${tag}/>`;
}

/// Resolve a spec name to its lucide node list. The JSON keys icons by the (camelCase) spec
/// name directly; `_aliases` maps a spec name to its lucide key as a fallback for any name not
/// stored under its own key.
function resolveNodes(name, icons, aliases) {
  if (icons[name]) return icons[name];
  const alias = aliases[name];
  if (alias && icons[alias]) return icons[alias];
  return null;
}

function generate() {
  const names = specIconNames();
  if (names.length === 0) throw new Error("gen-lucide-icons: no icon names found in spec.rs");
  const data = JSON.parse(fs.readFileSync(LUCIDE, "utf8"));
  const icons = data.icons || {};
  const aliases = data._aliases || {};

  // Build the match arms; fail loudly if a spec name has no SVG data (the gate would fail on
  // data-icon-missing, so generation must refuse to ship an incomplete file).
  const arms = [];
  const missing = [];
  for (const name of names) {
    const nodes = resolveNodes(name, icons, aliases);
    if (!nodes) {
      missing.push(name);
      continue;
    }
    const inner = nodes.map(nodeMarkup).join("");
    if (!/<(?:path|rect|circle|ellipse|line|polyline|polygon)\b/.test(inner)) {
      throw new Error(`gen-lucide-icons: ${name} has no shape element: ${inner}`);
    }
    arms.push(`        ${JSON.stringify(name)} => Some(r###"${inner}"###),`);
  }
  if (missing.length > 0) {
    throw new Error(`gen-lucide-icons: no lucide data for: ${missing.join(", ")}`);
  }

  const namesList = names.map((n) => `    ${JSON.stringify(n)},`).join("\n");
  const src = `//! GENERATED by tools/gen-lucide-icons.mjs — do not edit; regenerate with \`node tools/gen-lucide-icons.mjs\`.
//! Lucide (ISC, https://lucide.dev) SVG inner markup for every icon named by
//! \`src/ribbon/spec.rs\`. \`svg(name)\` returns the shape nodes; \`control.rs\` wraps them in a
//! 16×16 \`<svg>\` with lucide's default stroke attributes.

/// Sorted, unique list of every icon name \`svg\` can render. The non-test build does not read it
/// directly (\`control.rs\` calls \`svg\`), so silence dead_code; the test module asserts it.
#[allow(dead_code)]
pub const NAMES: &[&str] = &[
${namesList}
];

/// Inner SVG markup (the \`<path>/<circle>/<rect>/<line>\` nodes) for \`name\`, or \`None\` if
/// \`name\` is not a known icon. \`control.rs\` wraps this in the full \`<svg>\` element.
pub fn svg(name: &str) -> Option<&'static str> {
    match name {
${arms.join("\n")}
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ribbon::spec;
    use crate::types::Kind;

    fn icon_name(k: &Kind) -> Option<&'static str> {
        match k {
            Kind::Button { icon, .. } => Some(icon),
            Kind::Dropdown { icon: Some(i), .. } => Some(i),
            _ => None,
        }
    }

    #[test]
    fn every_spec_icon_resolves_to_a_shape() {
        let mut seen = 0;
        for tab in spec::tabs() {
            for g in &tab.groups {
                for c in &g.controls {
                    if let Some(name) = icon_name(&c.kind) {
                        seen += 1;
                        let s = svg(name).unwrap_or_else(|| panic!("no svg for {name}"));
                        assert!(
                            s.contains("<path")
                                || s.contains("<circle")
                                || s.contains("<rect")
                                || s.contains("<line")
                                || s.contains("<polyline")
                                || s.contains("<polygon")
                                || s.contains("<ellipse"),
                            "svg for {name} has no shape element: {s}"
                        );
                    }
                }
            }
        }
        assert!(seen > 0, "no icon-bearing controls found in spec");
    }

    #[test]
    fn names_are_sorted_and_unique() {
        let mut sorted = NAMES.to_vec();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(NAMES, sorted.as_slice(), "NAMES is not sorted/unique");
    }

    #[test]
    fn svg_returns_none_for_unknown() {
        assert!(svg("NotAnIcon").is_none());
    }

    #[test]
    fn every_name_resolves() {
        for name in NAMES {
            assert!(svg(name).is_some(), "NAMES lists {name} but svg returns None");
        }
    }
}
`;

  return src;
}

function rustfmt(src) {
  const r = spawnSync("rustfmt", ["--edition", "2021", "--emit", "stdout"], {
    input: src,
    encoding: "utf8",
  });
  if (r.status !== 0) throw new Error(`gen-lucide-icons: rustfmt failed:\n${r.stderr}`);
  return r.stdout;
}

const src = generate();
const formatted = rustfmt(src);

if (CHECK) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== formatted) {
    console.error(
      `gen-lucide-icons: ${path.relative(ROOT, OUT)} is stale — run: node tools/gen-lucide-icons.mjs`
    );
    process.exit(1);
  }
  console.log(`gen-lucide-icons: up to date (${specIconNames().length} icons)`);
} else {
  fs.writeFileSync(OUT, formatted);
  console.log(`gen-lucide-icons: wrote ${path.relative(ROOT, OUT)} (${specIconNames().length} icons)`);
}
