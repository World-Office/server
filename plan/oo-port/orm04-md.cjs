#!/usr/bin/env node
// ORM-04 md report generator — reads engine-internals.json and emits the
// engine-internals.md engine-internals gap report.
const fs = require("fs");
const a = JSON.parse(fs.readFileSync("plan/oo-port/engine-internals.json", "utf8"));

const L = [];
const w = (s) => L.push(s);

const sevName = ["covered", "partial", "missing", "engine-critical-missing"];
const sevCount = [0, 0, 0, 0];
for (const e of a) sevCount[e.gap_severity]++;
const families = {};
for (const e of a) {
  const f = e.oo_area.split("/")[0];
  families[f] = families[f] || { rows: 0, cls: 0, fn: 0, sev: [0, 0, 0, 0] };
  families[f].rows++;
  families[f].cls += e.oo_class_estimate;
  families[f].fn += e.oo_fn_estimate;
  families[f].sev[e.gap_severity]++;
}
const s3 = a.filter((e) => e.gap_severity === 3);
const crateOf = (e) => e.wo_crate;

w("# OO core engine (DesktopEditor) → WO renderer crates — engine internals gap list");
w("");
w("Task ORM-04 of the oo-rust-map campaign. This report maps OnlyOffice's");
w("native editing-engine internals — the C++ tree under `core/DesktopEditor/` in");
w("the Euro-Office reference checkout — onto World-Office's Rust renderer stack,");
w("and produces the **gap list** a 1:1 wasm port must close for");
w("canvas-accurate editing/rendering parity.");
w("");
w("Artifacts:");
w("");
w("- `plan/oo-port/engine-internals.json` — one row per DesktopEditor area");
w("  (path segment under `DesktopEditor/`), with cgc class/function counts and");
w("  the WO verdict.");
w("- this report.");
w("");
w("Severity scale used in both artifacts:");
w("");
w("| sev | meaning |");
w("|-----|---------|");
w("| 0 | covered — a WO crate already implements the equivalent functionality |");
w("| 1 | partial — WO implements a subset; fidelity/perf gaps remain |");
w("| 2 | missing — no WO counterpart; needed for parity but not canvas-blocking |");
w("| 3 | engine-critical-missing — blocks canvas-accurate editing/rendering parity |");
w("");
w("## 1. Method (reproducible)");
w("");
w("Counts were produced live from the local code graph with the `cgc` CLI");
w("(CodeGraphContext, neo4j backend) over the Euro-Office core checkout at");
w("`/home/weiss/git/Euro-Office/core` (3227 classes / 38208 functions under");
w("`DesktopEditor/` — matches the campaign's CGC-indexed baseline).");
w("");
w("Class counts per two-level area:");
w("");
w("```cypher");
w('MATCH (c:Class) WHERE c.path CONTAINS "/DesktopEditor/"');
w('WITH split(split(c.path, "/DesktopEditor/")[1], "/")[0] AS a1,');
w('     split(split(c.path, "/DesktopEditor/")[1], "/")[1] AS a2,');
w("     count(c) AS classes ORDER BY a1 DESC, classes DESC");
w("RETURN a1, a2, classes");
w("```");
w("");
w("Function counts per two-level area: same query over `(f:Function)`.");
w("The JSON union of both result sets is **" + a.length + " areas**.");
w("");
w("WO-side verdicts were made by reading this worktree's crates, not guessed:");
w("");
w("| crate | lines | what it actually implements (read for this report) |");
w("|-------|-------|-----------------------------------------------------|");
w("| wo-renderer | 3865 | `Canvas` (save/restore, transforms, solid/gradient paint, blend modes, single clip path, scanline fill/stroke, `draw_text` via **rustybuzz** shaping + **swash** glyph raster), `TextLayoutEngine` (`char_advance`-based, **no shaping**), `FontLibrary` (fontdb) |");
w("| wo-renderer-wasm | 8829 | `init`, `render_page`, `create_document`, `layout_document`, `render_laid_out_page`, mouse/key editing, selection, undo/redo, formatting ops, `spell_*` exports incl. hyphenation; `layout.rs` lays out `DocxBlock::Image` as a **no-op placeholder**; `canvas_bridge.rs` bundles Liberation fonts and bridges `Canvas` to web canvas |");
w("| wo-fonts | 1155 | ttf-parser face loader, `FontCache`/`FontMatcher` (family/weight), `FontMetrics` (ascent/descent/underline/strike) — **no glyph raster cache, no hinting, no system font scan** |");
w("| wo-spell | 2784 | hunspell-style aff/dic, suggestions, **Liang hyphenation** (`hyphenate.rs`) |");
w("| wo-raster | 667 | `ImageDecoder`/`ImageEncoder` over the `image` crate (png/jpeg/tiff/gif/bmp), `RasterImage` RGBA model, format magic sniffing |");
w("| wo-common | 2254 | document/format registry, doc-tree path addressing, units (EMU matrix), encoding — **no base64, no CRC32** |");
w("| wo-ooxml | 12385 | OOXML model/parser/serializer over **roxmltree** (read-only DOM) |");
w("");
w("Workspace deps confirm the shaping/raster situation: `rustybuzz = 0.20`,");
w("`swash = 0.2`, `fontdb = 0.16`, `ttf-parser = 0.25`,");
w("`image = { 0.25, features = [png, jpeg, tiff, gif, bmp] }`, `roxmltree = 0.20`.");
w("");
w("## 2. Totals");
w("");
w("Severity histogram over " + a.length + " areas: **" + sevCount[0] + " covered / " + sevCount[1] +
  " partial / " + sevCount[2] + " missing / " + sevCount[3] + " engine-critical-missing**.");
w("");
w("| family | areas | classes | fns | sev0 | sev1 | sev2 | sev3 |");
w("|--------|------:|--------:|----:|-----:|-----:|-----:|-----:|");
for (const [f, v] of Object.entries(families)) {
  w(`| ${f} | ${v.rows} | ${v.cls} | ${v.fn} | ${v.sev[0]} | ${v.sev[1]} | ${v.sev[2]} | ${v.sev[3]} |`);
}
w("| **total** | **" + a.length + "** | **" + Object.values(families).reduce((s, v) => s + v.cls, 0) +
  "** | **" + Object.values(families).reduce((s, v) => s + v.fn, 0) + "** | **" + sevCount[0] + "** | **" + sevCount[1] +
  "** | **" + sevCount[2] + "** | **" + sevCount[3] + "** |");
w("");
w("Read of the totals:");
w("");
w("- `raster` is the biggest family (1018 classes / 9726 fns) and the worst");
w("  asymmetry: WO's 667-line wo-raster handles the common bitmap formats only.");
w("- `agg-2.4` + `graphics` together are OO's rasterization brain (714 classes /");
w("  6709 fns); WO's Canvas covers the easy 20% of it.");
w("- `xml` (412/5934) is mostly vendored libxml2; roxmltree replaces parsing but");
w("  nothing replaces XPath/XInclude.");
w("- `freetype-2.10.4`/`freetype_names` are largely *replaced*, not ported:");
w("  ttf-parser/fontdb/swash cover parsing, metrics and glyph rasterization");
w("  (minus bytecode hinting).");
w("- `fontengine` is where text parity lives (53 classes, all load-bearing).");
w("");
w("## 3. Area table");
w("");
w("All " + a.length + " areas (full detail incl. per-area notes is in");
w("`engine-internals.json`). sevw = WO crate the area maps to (NONE = nothing).");
w("");
w("| oo_area | classes | fns | wo_crate | sev |");
w("|---------|--------:|----:|----------|----:|");
for (const e of a) {
  w(`| ${e.oo_area} | ${e.oo_class_estimate} | ${e.oo_fn_estimate} | ${crateOf(e)} | ${e.gap_severity} |`);
}
w("");
w("## 4. Severity-3 areas — engine-critical gaps (full list)");
w("");
w("These block canvas-accurate editing/rendering parity; each needs a designed");
w("Rust counterpart before a 1:1 wasm port can claim parity. One-line rationale");
w("each (fuller notes per row in the JSON):");
w("");
s3.forEach((e, i) => {
  w(`${i + 1}. **${e.oo_area}** (${e.oo_class_estimate} cl / ${e.oo_fn_estimate} fns → ${e.wo_crate}) — ${e.notes.replace(/ \(source: DesktopEditor\/[^)]*\)$/, "")}`);
});
w("");
w("Grouped, the 19 severity-3 rows are really **six** engine capabilities:");
w("");
w("1. **Image blitting on the canvas** (`graphics/Image.*`) — a document without");
w("   pictures is not a document; today every image is skipped in `layout.rs`.");
w("2. **Vector metafiles** (`raster/Metafile`, `graphics/commands`,");
w("   `graphics/MetafileTo*`) — EMF/WMF/EMF+ parse + replay-to-renderer.");
w("3. **Boolean path ops** (`agg-2.4/gpc`, `graphics/BooleanOperations.*`) —");
w("   merge/subtract/intersect for shape editing.");
w("4. **High-grade rasterization** (`agg-2.4/include`) — Agg-quality AA,");
w("   stroke joins/dashes, image resampling filters, compound rasterizer.");
w("5. **Text layout with shaping** (`fontengine/GlyphString.*`) — kerned,");
w("   ligated, bidi-aware measurement feeding line breaking; rustybuzz exists");
w("   but only on the `Canvas::draw_text` path, not in `TextLayoutEngine`.");
w("6. **Format codecs & host**: JPEG2000 (`raster/Jp2`, `cximage/jasper`), SVG");
w("   (`agg-2.4/svg`), server-side JS host (`doctrenderer/js_internal`).");
w("");
w("## 5. Recommended new Rust modules");
w("");
w("New modules/crates, in priority order (name → absorbs which severity-3 rows):");
w("");
w("| new module | absorbs | note |");
w("|------------|---------|------|");
w("| `wo-renderer::textlayout` | fontengine/GlyphString.*, wasm layout.rs line breaking | real line breaker consuming shaped runs; tab stops, alignment, baseline grid; the current `TextLayoutEngine` stays as the fallback |");
w("| `wo-renderer::shaping` | fontengine/TextShaper.* (currently sev-1) | promote rustybuzz+swash from `Canvas::draw_text` internals into a first-class `Shaper` API: `shape(text, font, size, script, dir) -> GlyphRun`, consumed by `textlayout`; adds bidi segmentation (wo-unicode has the tables) |");
w("| `wo-renderer::draw_image` (Canvas method) | graphics/Image.*, ImageFilesCache | `draw_image(&RasterImage, dst_rect, src_rect, transform, alpha)` + resampling (bilinear first, Agg-style filters later) + an id→frame cache |");
w("| `wo-renderer::boolops` | graphics/BooleanOperations.*, agg-2.4/gpc | polygon boolean ops (union/intersect/diff) over `PathBuilder`; port gpc.c or adopt `pathfinding`-style clipper crate |");
w("| `wo-renderer::stroke` | agg-2.4/include (stroke slice) | proper stroke generator: joins (miter/round/bevel), caps, dash arrays — the Agg `vcgen_stroke`/`math_stroke` equivalents |");
w("| `wo-metafile` (new crate) | raster/Metafile, graphics/commands, graphics/MetafileTo* | EMF/WMF/EMF+ record parser + an `interpret(renderer)` replay trait; render target = wo-renderer Canvas |");
w("| `wo-raster::jp2` | raster/Jp2, cximage/jasper | JPEG2000 decode (bind or port OpenJPEG-lite); starts with JP2 container + code-stream decode to RGBA |");
w("| `wo-raster::svg` or `wo-svg` | agg-2.4/svg | SVG → PathBuilder/Gradient/Canvas pipeline (parse via roxmltree already in-tree) |");
w("| `wo-fonts::glyphcache` | fontengine/FontFile.*, FontManager.*, agg-2.4/font_freetype | LRU glyph raster cache keyed by (face, gid, size, transform), hinting on/off; feeds both canvas and textlayout |");
w("| `wo-common::base64` + `wo-common::crc32` | common/Base64.cpp, CalculatorCRC32.h | trivial, needed by metafile/zip/signature paths |");
w("| `wo-script` (decision needed) | doctrenderer/js_internal | server-side JS host for formulas/macros in wo-x2t; options: embed quickjs/rusty-v8, or declare browser-only and drop from server parity scope |");
w("");
w("Not recommended to port: `agg-2.4/examples`, `freetype-2.10.4/builds`,");
w("`vboxtester`, the docbuilder language bindings (java/python/com/net) — dead");
w("weight for a Rust/wasm port (all sev-0 in the JSON with that rationale).");
w("");
w("## 6. How wo-renderer-wasm grows to absorb the gaps");
w("");
w("The wasm crate already has the right *shape* for this: model-in");
w("(`create_document`/`create_model`) → layout (`layout.rs`, `layout_document`)");
w("→ render (`render_page`, `render_laid_out_page`, `layout_and_render`) →");
w("edit (mouse/key/insert/apply_formatting/undo/redo) → out");
w("(`serialize_document`, `get_selection_rects`, `get_cursor_position`), plus");
w("`canvas_bridge.rs` for web-canvas output and `spell_*` exports for");
w("wo-spell. The gaps land in it as follows:");
w("");
w("1. **Phase A — images (unblocks the loudest parity bug).** Add");
w("   `Canvas::draw_image` in wo-renderer, then stop skipping");
w("   `DocxBlock::Image` in `wo-renderer-wasm/src/layout.rs` (currently a");
w("   literal `=> {}` with the \"DM-7\" placeholder comment). Needs a wasm");
w("   export to feed decoded image bytes/handles; `canvas_bridge.rs` gains an");
w("   `ImageData` blit path.");
w("2. **Phase B — textlayout/shaping.** Extract a `Shaper` from");
w("   `canvas.rs::draw_text`, wire it into `TextLayoutEngine`, and replace the");
w("   `char_advance` line breaking used by `layout.rs` with shaped-run line");
w("   breaking. This changes no wasm signatures — `layout_document` output");
w("   just becomes correct for kerned/complex text.");
w("3. **Phase C — rasterization quality.** Swap the hand-rolled scanline");
w("   filler for an Agg-grade rasterizer behind the same `Canvas` API");
w("   (stroke joins/dashes + AA cells + clip stack); canvas_bridge keeps");
w("   working because the API surface is unchanged.");
w("4. **Phase D — metafile/svg/jp2 decode.** New crates expose `decode →");
w("   RasterImage | command list`; the wasm crate routes `DocxBlock::Image`");
w("   payloads through them exactly like PNG/JPEG today.");
w("5. **Phase E — boolean ops + JS host** for shape editing and server-side");
w("   formulas; the wasm boundary needs new exports (`apply_structure_op`");
w("   already exists as the shape-op hook point; a `formula_eval` export");
w("   would hang off the Phase-E JS host decision).");
w("");
w("## 7. Follow-ups");
w("");
w("- Severity-3 is **19 rows / 6 capabilities** — Phase A (images) is the");
w("  smallest diff with the largest visual payoff and should be filed first");
w("  (it is already named as DM-7 in the wasm crate).");
w("- `fontengine/TextShaper` is only sev-1 *because* rustybuzz exists; the");
w("  gap is wiring, not capability. textlayout+shaping are the two new");
w("  wo-renderer modules to land for Phase B.");
w("- wo-unicode (1039 lines, not part of the campaign's crate list) already");
w("  carries bidi-related tables that Phase B shaping will consume.");
w("- A same-method re-run of the two cypher queries in §1 regenerates the");
w("  counts; the JSON was produced by merging them with a curated verdict");
w("  table (`orm04-build.cjs`, kept next to the artifacts for reproducibility).");
w("");

fs.writeFileSync("plan/oo-port/engine-internals.md", L.join("\n") + "\n");
console.log("lines:", L.length);
